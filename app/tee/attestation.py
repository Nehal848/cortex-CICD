"""
TEE Remote Attestation
~~~~~~~~~~~~~~~~~~~~~~~~
Generates a remote attestation report (simulated Intel SGX EPID/DCAP format).
The report includes:
  - MRENCLAVE and MRSIGNER measurements
  - A nonce to prevent replay attacks
  - A timestamp
  - An RSA signature over the report body
  - Verification status

In real SGX, the attestation quote is generated by the Quoting Enclave (QE)
and verified against Intel's Attestation Service (IAS) or DCAP CAs.
"""

import os
import json
import hashlib
import logging
from datetime import datetime, timezone

logger = logging.getLogger(__name__)

_report_cache: dict | None = None
_report_generated_at: datetime | None = None
_CACHE_TTL_SECS = 300  # re-generate attestation every 5 minutes


def generate_attestation_report(nonce: str | None = None) -> dict:
    """
    Generate (or return cached) remote attestation report.

    Parameters
    ----------
    nonce : str, optional
        Challenge nonce from the verifier. If None, one is generated.

    Returns
    -------
    dict
        Full attestation report with measurements, signature, and status.
    """
    global _report_cache, _report_generated_at

    import time
    now = datetime.now(timezone.utc)

    # Return cached report if fresh
    if (_report_cache is not None and _report_generated_at is not None and
            (time.time() - _report_generated_at.timestamp()) < _CACHE_TTL_SECS and
            nonce is None):
        return _report_cache

    from . import enclave
    mrenclave = enclave.get_mrenclave()
    mrsigner  = enclave.get_mrsigner()

    if nonce is None:
        nonce = os.urandom(16).hex()

    report_body = {
        "version":    "2",
        "isv_svn":    1,
        "mrenclave":  mrenclave,
        "mrsigner":   mrsigner,
        "timestamp":  now.isoformat(),
        "nonce":      nonce,
        "platform":   "Intel SGX (Simulated)",
        "tcb_status": "UpToDate",
    }

    # Sign the report body (simulated: SHA-256 HMAC over body using enclave key)
    body_bytes = json.dumps(report_body, sort_keys=True).encode()
    signature  = _sign_report(body_bytes)

    # Verify inline (always passes in simulation)
    verified = _verify_signature(body_bytes, signature)

    report = {
        **report_body,
        "signature":           signature,
        "signature_algorithm": "HMAC-SHA256 (simulated RSA-PSS in production)",
        "verification_status": "VERIFIED" if verified else "FAILED",
        "ias_report_id":       hashlib.sha256(body_bytes[:32]).hexdigest()[:24],
        "advisory_ids":        [],
        "security_score":      _compute_security_score(report_body),
    }

    _report_cache        = report
    _report_generated_at = now
    return report


def verify_attestation(report: dict) -> dict:
    """
    Verify an attestation report.
    Returns verification result with pass/fail details.
    """
    checks = {}

    # Check measurements match current enclave
    from . import enclave
    checks["mrenclave_match"] = report.get("mrenclave") == enclave.get_mrenclave()
    checks["mrsigner_match"]  = report.get("mrsigner")  == enclave.get_mrsigner()
    checks["tcb_ok"]          = report.get("tcb_status") == "UpToDate"
    checks["timestamp_fresh"] = _check_timestamp_fresh(report.get("timestamp", ""))
    checks["nonce_present"]   = bool(report.get("nonce"))

    # Re-verify signature
    from . import enclave as _enc
    body = {k: v for k, v in report.items()
            if k not in ("signature", "verification_status", "ias_report_id",
                         "advisory_ids", "security_score", "signature_algorithm")}
    body_bytes = json.dumps(body, sort_keys=True).encode()
    sig = report.get("signature", "")
    checks["signature_valid"] = _verify_signature(body_bytes, sig)

    all_passed = all(checks.values())
    return {
        "passed":  all_passed,
        "status":  "VERIFIED" if all_passed else "FAILED",
        "checks":  checks,
    }


# ── Helpers ────────────────────────────────────────────────────────

def _sign_report(body_bytes: bytes) -> str:
    """HMAC-SHA256 over report body using enclave key (simulates RSA signature)."""
    import hmac
    from . import enclave
    mac = hmac.new(enclave._key(), body_bytes, hashlib.sha256)
    return mac.hexdigest()


def _verify_signature(body_bytes: bytes, signature: str) -> bool:
    try:
        import hmac
        from . import enclave
        expected = hmac.new(enclave._key(), body_bytes, hashlib.sha256).hexdigest()
        return hmac.compare_digest(expected, signature)
    except Exception:
        return False


def _check_timestamp_fresh(ts: str, max_age_secs: int = 3600) -> bool:
    try:
        from datetime import datetime, timezone
        t = datetime.fromisoformat(ts)
        delta = (datetime.now(timezone.utc) - t).total_seconds()
        return 0 <= delta <= max_age_secs
    except Exception:
        return False


def _compute_security_score(report: dict) -> int:
    """Compute a security score 0-100 based on attestation report fields."""
    score = 70  # base
    if report.get("tcb_status") == "UpToDate":
        score += 15
    if report.get("isv_svn", 0) >= 1:
        score += 10
    if not report.get("advisory_ids"):
        score += 5
    return min(score, 100)
